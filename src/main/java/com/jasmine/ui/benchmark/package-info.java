/**
 * Benchmark execution and results views for JASMINE.
 *
 * <p>This package contains the JavaFX views and supporting controllers for
 * configuring, launching, and reviewing JVM benchmark runs. It provides a
 * complete workflow spanning the full benchmark lifecycle:
 *
 * <ul>
 *   <li><strong>Configuration Panel</strong> — form-based UI for selecting benchmark
 *       type (memory, computation, concurrency, I/O), setting iteration counts,
 *       warm-up durations, and specifying target JVM flags</li>
 *   <li><strong>Execution Monitor</strong> — a live progress view showing the
 *       current iteration, elapsed time, estimated time remaining, and a progress
 *       bar, updated via events from the {@link com.jasmine.event} bus</li>
 *   <li><strong>Results Table</strong> — a sortable, filterable table displaying
 *       per-iteration timing, memory, and throughput measurements alongside
 *       summary statistics (mean, median, p95, p99)</li>
 *   <li><strong>Results Charts</strong> — embedded visualizations generated by the
 *       {@link com.jasmine.chart} package showing iteration-over-time trends,
 *       distribution histograms, and comparative overlays</li>
 *   <li><strong>History Browser</strong> — access to previously executed benchmarks
 *       for comparison and regression detection</li>
 * </ul>
 *
 * <p>Views in this package delegate all business logic to the
 * {@link com.jasmine.service} layer and all benchmark execution to the
 * {@link com.jasmine.benchmark} engine.
 *
 * @since 1.0
 */
package com.jasmine.ui.benchmark;
